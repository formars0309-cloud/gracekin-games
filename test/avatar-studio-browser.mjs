// 실행: PLAYWRIGHT_MODULE=설치된모듈경로 node test/avatar-studio-browser.mjs
// 임시 서버·회원만 사용한다. AVATAR_CAPTURE_DIR을 지정하면 실제 화면을 보관한다.
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { startServer } from '../server/app.js';
import { registerAndLogin } from './account-helpers.js';

const { chromium, webkit } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const engine = process.env.AVATAR_BROWSER === 'webkit' ? webkit : chromium;
const folder = await mkdtemp(join(tmpdir(), 'avatar-studio-browser-'));
const captures = process.env.AVATAR_CAPTURE_DIR;
const mailbox = [];
let app, browser;
try {
  app = await startServer({ port: 0, dataDir: folder, mailer: async mail => mailbox.push(mail), guardianReplyTo: 'guardian@example.test' });
  browser = await engine.launch({ executablePath: process.env.BROWSER_EXECUTABLE || undefined });
  const errors = [];
  const context = await browser.newContext({ viewport: { width: 1320, height: 890 }, reducedMotion: 'reduce' });
  // 시험 실행이 외부 분석·글꼴 서비스 상태에 의존하지 않게 한다.
  await context.route(/^https:\/\//, route => route.abort());
  let page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  const $ = selector => page.locator(selector);
  const checkName = value => page.waitForFunction(expected => document.querySelector('#hero-name').value === expected, value);
  const capture = async title => {
    if (!captures) return;
    await mkdir(captures, { recursive: true });
    await page.screenshot({ path: join(captures, title + '.png'), fullPage: true });
  };
  await page.goto(app.origin + '/games/avatar/');
  await $('#login').waitFor({ state: 'visible' });
  await page.waitForFunction(() => document.querySelectorAll('#presets canvas').length === 3 && document.querySelector('#render-status').hidden);
  if (process.env.AXE_SOURCE) {
    await page.addScriptTag({ path: process.env.AXE_SOURCE });
    const failures = await page.evaluate(async () => (await window.axe.run(document, { runOnly: ['wcag2a','wcag2aa','wcag21aa'] })).violations.map(item => ({ id: item.id, targets: item.nodes.map(node => node.target) })));
    assert.deepEqual(failures, []);
  }
  await capture('작업대');
  await $('#hero-name').fill('새벽별');
  await $('[data-job=ranger]').click();
  await $('[data-preset="1"]').click();
  await checkName('새벽별');
  assert.equal(await $('[data-job=ranger]').getAttribute('aria-pressed'), 'true');
  await $('#undo').click();
  assert.equal(await $('[data-preset="0"]').getAttribute('aria-pressed'), 'true');
  await $('#redo').click();
  assert.equal(await $('[data-preset="1"]').getAttribute('aria-pressed'), 'true');
  await $('[data-section=body]').click();
  await $('#height').focus();
  await page.keyboard.press('End');
  assert.equal(await $('#height-value').textContent(), '100');
  await $('[data-section=face]').click();
  await $('[data-hair="3"]').click();
  await $('[data-section=color]').click();
  await $('#clothColor').fill('#aa6633');
  await $('#zoom').click();
  assert.equal(await $('#zoom').getAttribute('aria-pressed'), 'true');
  await $('#rotate-left').click();
  await $('#rotate-right').click();
  await $('#motion').click();
  await $('#motion').click();
  await $('button[data-mode=portrait]').click();
  assert.match(await $('#avatar-view [role=img]').getAttribute('aria-label'), /얼굴/);
  await $('button[data-mode=board]').click();
  const start = await $('#travel-hint').textContent();
  await $('#scene').press('ArrowRight');
  assert.notEqual(await $('#travel-hint').textContent(), start);
  await $('[data-direction=left]').click();
  assert.equal(await $('#travel-hint').textContent(), start);
  await capture('보드판');
  await $('button[data-mode=rpg]').click();
  const left = await $('#avatar-view').evaluate(node => node.style.left);
  await $('#scene').focus();
  await page.keyboard.down('ArrowRight');
  await page.waitForFunction(previous => document.querySelector('#avatar-view').style.left !== previous, left);
  await page.keyboard.up('ArrowRight');
  await capture('탐험');
  await $('[data-section=profile]').click();
  await $('#open-quiz').click();
  await $('#quiz-root input[type=radio]').first().waitFor();
  while (await $('#quiz-root input[type=radio]').count()) {
    await $('#quiz-root input[value=healer]').check();
    await $('#quiz-root button[type=submit]').click();
  }
  await page.getByRole('button', { name: '별빛치유사 적용' }).click();
  assert.equal(await $('[data-job=healer]').getAttribute('aria-pressed'), 'true');
  assert.match(await $('#recommendation').textContent(), /별빛치유사/);
  await page.reload();
  await checkName('새벽별');
  assert.match(await $('#recommendation').textContent(), /별빛치유사/);
  assert.equal(await $('#height').inputValue(), '100');
  assert.equal(await $('#clothColor').inputValue(), '#aa6633');
  const member = { email: 'ataraxia@example.test', password: randomUUID(), name: '공방 회원', ageBand: '14plus' };
  assert.equal((await registerAndLogin(app, mailbox, member)).status, 200);
  const loginPage = context.waitForEvent('page');
  await $('#login').click();
  const account = await loginPage;
  await account.locator('#signin-email').fill(member.email);
  await account.locator('#signin-password').fill(member.password);
  const signed = account.waitForResponse(response => response.url().endsWith('/api/auth/sign-in/email') && response.ok());
  await account.locator('#signin-form button[type=submit]').click();
  await signed;
  await account.close();
  await page.bringToFront();
  // 헤드리스 환경에서는 창 활성화 이벤트가 발생하지 않을 수 있다.
  if (!(await $('#use-guest').isVisible())) await $('#load').click();
  await $('#use-guest').waitFor({ state: 'visible' });
  assert.notEqual(await $('#hero-name').inputValue(), '새벽별');
  await $('#use-guest').click();
  await $('#save').click();
  await page.waitForFunction(() => document.querySelector('#sync-status').textContent.includes('계정에 저장했어요'));
  const savedAvatar = async () => (await (await context.request.get(app.origin + '/api/avatar/me')).json()).avatar;
  const saved = await savedAvatar();
  assert.equal(saved.character.appearance.height, 100);
  assert.equal(saved.character.appearance.clothColor, '#aa6633');
  assert.equal(saved.character.recommendedJob, 'healer');
  assert.equal(saved.character.name, '새벽별');
  await page.reload();
  await checkName('새벽별');
  await $('#hero-name').fill('내 편집본');
  const remote = await context.request.put(app.origin + '/api/avatar/me', { headers: { origin: app.origin }, data: { revision: saved.revision, character: { ...saved.character, name: '다른 창' } } });
  assert.equal(remote.status(), 200);
  await $('#save').click();
  await $('#conflict-actions').waitFor({ state: 'visible' });
  assert.equal(await $('#hero-name').inputValue(), '내 편집본');
  await $('#keep-local').click();
  await $('#save').click();
  await page.waitForFunction(() => document.querySelector('#sync-status').textContent.includes('계정에 저장했어요'));
  const updated = await savedAvatar();
  assert.equal(updated.id, saved.id);
  assert.equal(updated.revision, saved.revision + 2);
  assert.equal(updated.character.name, '내 편집본');
  await $('#hero-name').fill('취소한 변경');
  await $('#load').click();
  await $('#confirm-dialog button[value=cancel]').click();
  await checkName('취소한 변경');
  await $('#load').click();
  await $('#confirm-dialog button[value=ok]').click();
  await checkName('내 편집본');
  await $('#hero-name').fill('회원 비공개 초안');
  await context.clearCookies();
  await $('#load').click();
  await $('#login').waitFor({ state: 'visible' });
  assert.notEqual(await $('#hero-name').inputValue(), '회원 비공개 초안');
  assert.equal(await $('#undo').isDisabled(), true);
  await page.route('**/api/account/session', route => route.fulfill({ status: 503, body: '{}' }));
  await $('#load').click();
  await page.waitForFunction(() => document.querySelector('#sync-status').textContent.includes('기록을 확인하지 못했어요'));
  await page.unroute('**/api/account/session');
  const second = { ...member, email: 'ataraxia-second@example.test', password: randomUUID() };
  assert.equal((await registerAndLogin(app, mailbox, second)).status, 200);
  const signIn = async user => context.request.post(app.origin + '/api/auth/sign-in/email', { headers: { origin: app.origin }, data: { email: user.email, password: user.password } });
  assert.equal((await signIn(second)).status(), 200);
  await $('#load').click();
  await page.waitForFunction(() => !document.querySelector('#save').disabled);
  assert.notEqual(await $('#hero-name').inputValue(), '회원 비공개 초안');
  assert.equal(await savedAvatar(), null);
  await context.clearCookies();
  assert.equal((await signIn(member)).status(), 200);
  await $('#load').click();
  await checkName('회원 비공개 초안');
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  await mobile.route(/^https:\/\//, route => route.abort());
  page = await mobile.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(app.origin + '/games/avatar/#quiz');
  await $('#quiz-root input[type=radio]').first().waitFor();
  await page.keyboard.press('Escape');
  await $('button[data-mode=studio]').tap();
  await capture('모바일');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await $('[data-preset="1"]').tap();
  await $('button[data-mode=rpg]').tap();
  const original = await $('#avatar-view').evaluate(node => node.style.top);
  await $('[data-direction=up]').tap();
  await page.waitForFunction(previous => document.querySelector('#avatar-view').style.top !== previous, original);
  const redirected = await browser.newContext();
  await redirected.route('https://gracekingames.com/**', async route => {
    const local = new URL(route.request().url());
    const response = await context.request.get(app.origin + local.pathname);
    await route.fulfill({ response });
  });
  await redirected.route('https://community.gracekingames.com/**', route => route.fulfill({ contentType: 'text/html', body: '<title>공방 도착</title>' }));
  await redirected.route(/https:\/\/(cloud\.umami\.is|fonts\.)/, route => route.abort());
  const entry = await redirected.newPage();
  await entry.goto('https://gracekingames.com/games/avatar/?mode=quiz', { waitUntil: 'commit' });
  await entry.waitForURL('https://community.gracekingames.com/games/avatar/#quiz');
  await redirected.close();
  assert.deepEqual(errors, []);
  console.log('공방 브라우저 검수 통과 · 외형·직업·보드판·탐험·손님 초안·계정 로그인·저장 충돌·390px 화면');
} finally {
  await browser?.close();
  await app?.close();
  await rm(folder, { recursive: true, force: true });
}
