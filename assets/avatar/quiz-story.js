export function scoreJourney(answers) {
  if (!Array.isArray(answers) || answers.length !== questions.length) throw new Error('열 장면의 선택이 필요해요.');
  const scores = { guardian: 0, ranger: 0, arcanist: 0, healer: 0 };
  for (const [index, job] of answers.entries()) {
    if (!Object.hasOwn(questions[index].choices, job)) throw new Error('장면에 있는 행동을 골라 주세요.');
    scores[job] += 1;
  }
  const highest = Math.max(...Object.values(scores));
  const tied = Object.keys(scores).filter(job => scores[job] === highest);
  const job = answers.find(answer => tied.includes(answer));
  return { job, scores, tied };
}
